class FakeAdapter:
    def __init__(self, label, response=None, error=None):
        self.label = label
        self.response = response
        self.error = error
        self.calls = []

    def generate(self, **kwargs):
        self.calls.append(kwargs)

        if self.error is not None:
            raise self.error

        return {
            "status": "GENERATED",
            "provider_id": self.label,
            "model_name": self.label,
            "response": self.response or f"Generated by {self.label}.",
            "metrics": {},
        }


def make_service(primary):
    gateway = ModelGateway(default_model="gemini-cloud")
    gateway.register(
        "gemini-cloud",
        primary,
        capabilities=["response_generation"],
    )

    service = ResponseService(gateway=gateway)

    return service


def test_primary_success_does_not_use_fallback():
    primary = FakeAdapter("gemini")

    service = make_service(primary)

    result = service.generate(
        user_text="Explain digital payments.",
        intent="SUPPORT_REQUEST",
        verified_result={},
        source="support_system",
    )

    assert result["response"] == "Generated by gemini."
    assert result["model_id"] == "gemini-cloud"
    assert result["fallback_used"] is False
    assert result["fallback_chain"] == ["gemini-cloud"]
    assert primary.calls


def test_primary_failure_falls_back_to_openrouter():
    primary = FakeAdapter(
        "gemini",
        error=RuntimeError("Gemini unavailable"),
    )
    openrouter = FakeAdapter("openrouter")

    service = make_service(primary)
    service._fallback_adapters["openrouter-cloud"] = openrouter

    result = service.generate(
        user_text="Explain digital payments.",
        intent="SUPPORT_REQUEST",
        verified_result={},
        source="support_system",
    )

    assert result["response"] == "Generated by openrouter."
    assert result["model_id"] == "openrouter-cloud"
    assert result["fallback_used"] is True
    assert result["fallback_from"] == "gemini-cloud"
    assert result["fallback_chain"] == [
        "gemini-cloud",
        "openrouter-cloud",
    ]
    assert len(primary.calls) == 1
    assert len(openrouter.calls) == 1


